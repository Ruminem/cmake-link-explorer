/**
 * Works out how much of the build time each CMake target accounts for.
 *
 * The same join the linker map does, from the other side: the log knows
 * `libs/engine/CMakeFiles/engine.dir/engine.cpp.obj` took 203 ms, and CMake
 * knows that path belongs to target "engine". Three routes, most specific first:
 *
 *   1. CMake's layout, which puts a target's objects under <target>.dir/
 *   2. an output named exactly like the target's nameOnDisk
 *   3. the same stem, for when the log and the build tree came off different
 *      machines (libengine.a here, engine.lib there)
 *
 * @returns {Map<string, {compile: number, link: number, total: number,
 *                        edges: object[], slowest: object|null}>}
 *          keyed by target id; targets nothing was built for are simply missing.
 */
function matchTargets(targetModel, logModel) {
  const byArtifact = new Map();
  const byObjectDir = new Map();
  // Windows and the default macOS volume do not distinguish case, and CMake and
  // ninja need not agree on it. Comparing raw would drop the whole join.
  const fold = (text) => String(text || '').toLowerCase();

  for (const target of targetModel.targets.values()) {
    if (target.nameOnDisk) byArtifact.set(fold(target.nameOnDisk), target);
    byObjectDir.set(fold(target.name) + '.dir', target);
  }

  // Two targets can reduce to the same stem (foo.lib beside libfoo.a). Crediting
  // one of them would be a guess, so drop the stem and leave those to the exact
  // routes -- the rule the map join already follows.
  const byStem = new Map();
  const ambiguous = new Set();
  for (const target of targetModel.targets.values()) {
    if (!target.nameOnDisk) continue;
    const stem = artifactStem(target.nameOnDisk);
    if (!stem) continue;
    if (byStem.has(stem)) ambiguous.add(stem);
    else byStem.set(stem, target);
  }
  for (const stem of ambiguous) byStem.delete(stem);

  const matched = new Map();

  for (const edge of logModel.edges) {
    let target = null;

    for (const output of edge.outputs) {
      if (target) break;
      // Both separators appear: ninja writes forward slashes, but a path that
      // came through CMake on Windows can carry backslashes -- the same thing
      // that once stopped executables matching in the map join.
      const dir = /(?:^|[\\/])([^\\/]+)\.dir(?:[\\/]|$)/.exec(output);
      if (dir) target = byObjectDir.get(fold(dir[1]) + '.dir');
    }
    for (const output of edge.outputs) {
      if (target) break;
      target = byArtifact.get(fold(path.basename(output)));
    }
    // Only once every exact route has missed, and never for object files:
    // those keep their own names across platforms, so stemming app.cpp.obj
    // would credit it to a target called app rather than to the directory it
    // was compiled in.
    if (!target && edge.kind !== 'compile') {
      for (const output of edge.outputs) {
        if (target) break;
        target = byStem.get(artifactStem(path.basename(output)));
      }
    }
    if (!target) continue;

    let row = matched.get(target.id);
    if (!row) {
      row = { compile: 0, link: 0, total: 0, edges: [], slowest: null };
      matched.set(target.id, row);
    }
    if (edge.kind === 'compile') row.compile += edge.duration;
    else row.link += edge.duration;
    row.total += edge.duration;
    row.edges.push(edge);
    if (!row.slowest || edge.duration > row.slowest.duration) row.slowest = edge;
  }

  for (const row of matched.values()) {
    row.edges.sort((a, b) => b.duration - a.duration);
  }
  return matched;
}

// ---------------------------------------------------------------- diff

/**
 * Compares two logs edge by edge, keyed by output.
 *
 * @returns {{
 *   total: {before: number, after: number, delta: number},
 *   outputs: Array<{key, kind, before, after, delta, status}>
 * }}
 */
function diff(before, after) {
  const durations = (model) => {
    const map = new Map();
    // Keyed on the first output so a multi-output edge is one row, matching how
    // it is counted in the totals.
    for (const edge of model.edges) map.set(edge.outputs[0], edge);
    return map;
  };

  const beforeEdges = durations(before);
  const afterEdges = durations(after);
  const keys = new Set([...beforeEdges.keys(), ...afterEdges.keys()]);
  const outputs = [];

  for (const key of keys) {
    const b = beforeEdges.get(key);
    const a = afterEdges.get(key);
    const beforeMs = b ? b.duration : 0;
    const afterMs = a ? a.duration : 0;
    if (beforeMs === afterMs) continue;
    outputs.push({
      key,
      kind: (a || b).kind,
      before: beforeMs,
      after: afterMs,
      delta: afterMs - beforeMs,
      status: !b ? 'added' : !a ? 'removed' : 'changed'
    });
  }

  outputs.sort((x, y) => Math.abs(y.delta) - Math.abs(x.delta));

  return {
    total: {
      before: before.totals.cpu,
      after: after.totals.cpu,
      delta: after.totals.cpu - before.totals.cpu
    },
    outputs
  };
}

// Milliseconds are what the log carries and what short edges need, but a link
// measured in thousands of them is unreadable. Same ladder as formatBytes.
function formatMs(value) {
  const sign = value < 0 ? '-' : '';
  const ms = Math.abs(Math.round(value));
  if (ms < 1000) return sign + ms + ' ms';
  if (ms < 60000) return sign + (ms / 1000).toFixed(1) + ' s';
  const minutes = Math.floor(ms / 60000);
  const seconds = Math.round((ms % 60000) / 1000);
  // 1 m 60 s would be a rounding artefact, not a time.
  if (seconds === 60) return sign + (minutes + 1) + ' m 00 s';
  return sign + minutes + ' m ' + String(seconds).padStart(2, '0') + ' s';
}

